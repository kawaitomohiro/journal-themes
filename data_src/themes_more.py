def parse_more(block, prefix, start):
    out, cat = [], None
    n = start
    for line in block.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith('## '):
            cat = line[3:].strip()
            continue
        t, a, tags, per, stage = [x.strip() for x in line.split('|')]
        out.append({
            "n": n, "key": prefix + str(n), "cat": cat,
            "t": t, "a": a, "tags": tags.split(','), "per": per.split(','), "stage": stage,
        })
        n += 1
    return out


