def parse(block, prefix):
    out = []
    lines = [l for l in block.strip().splitlines() if l.strip()]
    assert len(lines) == 100, (prefix, len(lines))
    for i, line in enumerate(lines):
        t, a, tags, per, stage = [x.strip() for x in line.split('|')]
        out.append({
            "n": i + 1, "key": prefix + str(i + 1), "cat": CATS[i // 25],
            "t": t, "a": a, "tags": tags.split(','), "per": per.split(','), "stage": stage,
        })
    return out

